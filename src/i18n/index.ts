const tables: Record<Locale, Dict> = { ko, en, ja, zh, vi }

export const localeLabels: { id: Locale; label: string }[] = [
  { id: 'ko', label: '한국어' },
  { id: 'en', label: 'English' },
  { id: 'ja', label: '日本語' },
  { id: 'zh', label: '中文' },
  { id: 'vi', label: 'Tiếng Việt' },
]

export function translate(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  // localStorage가 손상돼 알 수 없는 locale이 들어오면 tables[locale]이 undefined라
  // 여기서 TypeError가 나고 화면이 통째로 백지가 된다. 사전 자체도 폴백한다.
  const table = tables[locale] ?? tables.ko
  let s = table[key] ?? tables.ko[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}

